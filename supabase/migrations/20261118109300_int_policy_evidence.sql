-- Full App v1, S2-INT part 4 of 4: a policy Yes needs no photo (FA-32; spec
-- §2, §4.2, §9.2; AC24, AC25).
--
-- S1-COV made six questions fact-only for coverage
-- (public.amenity_photo_requirements = none: guest_wifi, dogs_inside,
-- dogs_outside, live_music, pub_quiz, curbside_pickup), but the catalogue's
-- evidence rule still refused a Yes without a photo or video, so a manager
-- could not confirm the fact on its own.
--
--   Rule       a fifth evidence rule, none: media is optional for every
--              answer (private.amenity_rule_met is true). Allowed on the
--              catalogue, on submissions and on contributions (each keeps
--              the rule it was made under, so existing answers stay as they
--              were recorded and readable).
--   Catalogue  version 2 (supabase/seed/amenity_catalogue.csv, generated by
--              scripts/db/amenity-catalogue-sql.ts): the six questions move
--              to none; nothing else changes. Each of the six gains a
--              question version naming the rule (change_kind rule), and every
--              working slot notes the catalogue change (docs/knowledge G3).
--   Unchanged  the guest Wi-Fi rules (a manager confirms it, AC25; staff text
--              stays internal; a Yes still records its metadata and the
--              redaction confirmation), and photo evidence that is sent is
--              still kept with the answer.
--
-- Rollback: a forward migration restores the earlier evidence rules in a
-- catalogue version 3; the constraints may keep 'none'.

-- ---------------------------------------------------------------------------
-- The rule
-- ---------------------------------------------------------------------------

alter table public.amenity_catalogue drop constraint amenity_catalogue_evidence_rule_check;
alter table public.amenity_catalogue add constraint amenity_catalogue_evidence_rule_check
  check (evidence_rule in ('photo', 'video', 'either', 'both', 'none'));
alter table public.amenity_submissions drop constraint amenity_submissions_evidence_rule_check;
alter table public.amenity_submissions add constraint amenity_submissions_evidence_rule_check
  check (evidence_rule in ('photo', 'video', 'either', 'both', 'none'));
alter table public.knowledge_contributions drop constraint knowledge_contributions_evidence_rule_check;
alter table public.knowledge_contributions add constraint knowledge_contributions_evidence_rule_check
  check (evidence_rule in ('photo', 'video', 'either', 'both', 'none'));

create or replace function private.amenity_rule_met(p_rule text, p_kinds text[])
returns boolean
language sql
immutable
set search_path = ''
as $$
  select case p_rule
    when 'photo' then 'photo' = any(p_kinds)
    when 'video' then 'video' = any(p_kinds)
    when 'either' then 'photo' = any(p_kinds) or 'video' = any(p_kinds)
    when 'both' then 'photo' = any(p_kinds) and 'video' = any(p_kinds)
    when 'none' then true
    else false
  end;
$$;

