select (jsonb_populate_record(null::public.knowledge_question_versions,
  to_jsonb(v) || jsonb_build_object(
    'version', v.version + 1,
    'catalogue_version', 2,
    'evidence_rule', 'none',
    'effective_from', null,
    'created_at', now(),
    'created_by', null,
    'change_kind', 'rule',
    'change_note', 'S2-INT: media is optional for a Yes; the confirmed answer is enough (FA-32, catalogue version 2).'
  )
)).*
from public.knowledge_question_versions v
where v.key in ('guest_wifi', 'dogs_inside', 'dogs_outside', 'live_music', 'pub_quiz', 'curbside_pickup')
  and v.version = (select max(x.version) from public.knowledge_question_versions x where x.key = v.key);

