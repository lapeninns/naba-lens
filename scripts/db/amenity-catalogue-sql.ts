// Turns supabase/seed/amenity_catalogue.csv into the catalogue upsert block
// first embedded in supabase/migrations/20261107120000_amenity_catalogue.sql.
// The catalogue only changes through a new migration: edit the CSV, bump
// CATALOGUE_VERSION, run this and paste the output into a new migration. The
// block updates existing keys in place, so it re-runs over an earlier version;
// it never deletes a key (checks reference them). From version 2 the block
// also records a definition change for every key, so each knowledge slot's
// revision rises with its question version (docs/knowledge/b01-design.md G3).
//
//   pnpm exec tsx scripts/db/amenity-catalogue-sql.ts [csv]
import { readFileSync } from "node:fs"
import { fileURLToPath } from "node:url"

import { EVIDENCE_RULES, type EvidenceRule } from "../../lib/amenities/contract"

export const CATALOGUE_VERSION = 1
export const CATALOGUE_CSV = "supabase/seed/amenity_catalogue.csv"
export const BEGIN_MARKER =
  "-- BEGIN generated by scripts/db/amenity-catalogue-sql.ts"
export const END_MARKER = "-- END generated"

const HEADER = [
  "key",
  "category",
  "guest_question",
  "evidence_rule",
  "capture_brief",
  "is_core",
] as const

export type CatalogueCsvRow = {
  key: string
  category: string
  question: string
  evidenceRule: EvidenceRule
  captureBrief: string
  isCore: boolean
  /** 1-based CSV data row order. */
  position: number
}

/** RFC 4180 fields: quoted fields may hold commas, doubled quotes and newlines. */
function parseCsv(text: string): string[][] {
  const rows: string[][] = []
  let row: string[] = []
  let field = ""
  let quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]!
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"'
        i++
      } else if (c === '"') {
        quoted = false
      } else {
        field += c
      }
    } else if (c === '"' && field === "") {
      quoted = true
    } else if (c === ",") {
      row.push(field)
      field = ""
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++
      row.push(field)
      rows.push(row)
      row = []
      field = ""
    } else {
      field += c
    }
  }
  if (quoted) throw new Error("Unterminated quoted field")
  if (field !== "" || row.length > 0) {
    row.push(field)
    rows.push(row)
  }
  return rows
}

export function parseCatalogueCsv(text: string): CatalogueCsvRow[] {
  const [header, ...data] = parseCsv(text)
  if (header?.join(",") !== HEADER.join(",")) {
    throw new Error(`Unexpected header: ${header?.join(",")}`)
  }
  const keys = new Set<string>()
  return data.map((cells, index) => {
    const line = index + 2
    if (cells.length !== HEADER.length) {
      throw new Error(`Line ${line}: ${cells.length} fields`)
    }
    const [key, category, question, rule, brief, isCore] = cells.map((c) =>
      c.trim()
    ) as [string, string, string, string, string, string]
    if (!/^[a-z0-9_]{1,40}$/.test(key)) {
      throw new Error(`Line ${line}: invalid key "${key}"`)
    }
    if (keys.has(key)) throw new Error(`Line ${line}: duplicate key "${key}"`)
    keys.add(key)
    if (!(EVIDENCE_RULES as readonly string[]).includes(rule)) {
      throw new Error(`Line ${line}: invalid evidence rule "${rule}"`)
    }
    if (isCore !== "true" && isCore !== "false") {
      throw new Error(`Line ${line}: is_core must be true or false`)
    }
    for (const [name, value, max] of [
      ["category", category, 60],
      ["guest_question", question, 200],
      ["capture_brief", brief, 1000],
    ] as const) {
      if (value.length < 1 || value.length > max) {
        throw new Error(`Line ${line}: ${name} must be 1..${max} characters`)
      }
    }
    return {
      key,
      category,
      question,
      evidenceRule: rule as EvidenceRule,
      captureBrief: brief,
      isCore: isCore === "true",
      position: index + 1,
    }
  })
}

const literal = (value: string) => `'${value.replaceAll("'", "''")}'`

const COLUMNS = [
  "key",
  "category",
  "question",
  "capture_brief",
  "evidence_rule",
  "is_core",
  "position",
  "catalogue_version",
] as const

/** The exact block a catalogue migration embeds, markers included. */
export function catalogueInsertSql(
  rows: readonly CatalogueCsvRow[],
  version = CATALOGUE_VERSION
): string {
  const values = rows.map(
    (r) =>
      `  (${[
        literal(r.key),
        literal(r.category),
        literal(r.question),
        literal(r.captureBrief),
        literal(r.evidenceRule),
        String(r.isCore),
        String(r.position),
        String(version),
      ].join(", ")})`
  )
  return [
    BEGIN_MARKER,
    "insert into public.amenity_catalogue",
    `  (${COLUMNS.join(", ")})`,
    "values",
    values.join(",\n"),
    "on conflict (key) do update set",
    `${COLUMNS.filter((c) => c !== "key")
      .map((c) => `  ${c} = excluded.${c}`)
      .join(",\n")};`,
    ...(version > 1 ? definitionChangeSql(version) : []),
    END_MARKER,
  ].join("\n")
}

/** Version 1 predates the knowledge tables; later versions must note the change. */
function definitionChangeSql(version: number): string[] {
  return [
    "select private.knowledge_note_definition_change(c.key, 'question_version_changed')",
    "from public.amenity_catalogue c",
    `where c.catalogue_version = ${version}`,
    "order by c.key;",
  ]
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const csv = readFileSync(process.argv[2] ?? CATALOGUE_CSV, "utf8")
  process.stdout.write(`${catalogueInsertSql(parseCatalogueCsv(csv))}\n`)
}
