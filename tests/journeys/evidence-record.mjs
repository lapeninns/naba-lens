// Writes an evidence record from a journey run directory.
//
//   node tests/journeys/evidence-record.mjs <run-dir> --label <slug> [--out docs/qa/evidence] [--note <text>]
//
// Copies summary.json, summary.md and journeys/*.json (nothing else: no logs,
// screenshots, traces or session files) into
// <out>/<UTC date>-<short commit>-<label>/ and writes record.md there, with a
// per-id table derived from the catalogue in docs/qa/acceptance-ids.md. The
// record is generated from the result files, never typed by hand.
import { execFileSync } from "node:child_process"
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs"
import { dirname, join, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import {
  containsSecret,
  validateRunDir,
} from "../../scripts/ci/journeys/validate.mjs"
import { parseCatalogue } from "./acceptance-coverage.mjs"

/** Worst result wins: fail, then unavailable, then pass. `null` when nothing ran. */
export function aggregate(results) {
  if (results.length === 0) return null
  if (results.some((r) => r === "fail")) return "fail"
  if (results.some((r) => r === "unavailable")) return "unavailable"
  return "pass"
}

/**
 * How a result reads for one id. An observation that fails is "observation
 * reproduced", never a bug; a defect that fails is "defect reproduces".
 */
export function describeOutcome(kind, outcome) {
  if (outcome === null) return "not run"
  if (outcome === "unavailable") return "unavailable"
  if (kind === "observation") {
    return outcome === "fail"
      ? "fail: observation reproduced (not a defect)"
      : "pass: observation does not reproduce on this commit"
  }
  if (kind === "defect") {
    return outcome === "fail"
      ? "fail: defect reproduces on this commit"
      : "pass: defect does not reproduce on this commit"
  }
  return outcome
}

const describeEntry = (entry, outcome) =>
  entry.journeys.length === 0
    ? `no journey (${entry.status})`
    : describeOutcome(entry.kind, outcome)

const pnpmVersion = () => {
  try {
    const out = execFileSync("pnpm", ["--version"], { encoding: "utf8" })
    return `pnpm ${out.trim()}`
  } catch {
    return "pnpm (version not detected)"
  }
}

const cell = (text) =>
  String(text ?? "")
    .replace(/\|/g, "\\|")
    .replace(/\s*\n\s*/g, " ")

/**
 * @param {object} input
 * @param {object} input.summary parsed summary.json
 * @param {object[]} input.results parsed journeys/*.json
 * @param {{ entries: object[] }} input.catalogue
 * @param {{ node: string, pnpm: string, label: string, note?: string }} input.env
 */
export function renderRecord({ summary, results, catalogue, env }) {
  const { revision, stack } = summary
  const runner = [
    ...new Set(results.map((r) => `${r.runner.kind} ${r.runner.version}`)),
  ].join(", ")
  const byJourney = new Map(results.map((r) => [r.journey, r]))
  const lines = []
  const push = (...l) => lines.push(...l)

  push(
    `# Evidence record: ${env.label}`,
    "",
    "Generated by `tests/journeys/evidence-record.mjs` from the run's result files. It states what a run on this commit showed. It does not say anything about other commits.",
    "",
    "| Field | Value |",
    "| --- | --- |",
    `| Run id | \`${summary.runId}\` |`,
    `| Commit | \`${revision.commit}\` |`,
    `| Branch | \`${revision.branch}\` |`,
    `| Dirty | ${revision.dirty} |`,
    `| Stack | \`${stack.name}\` (API port ${stack.apiPort}) |`,
    `| Stack migrations | \`${stack.migrations}\` (latest applied version : digest prefix) |`,
    `| Runner | ${runner} |`,
    `| Node, pnpm | ${env.node}, ${env.pnpm} (on the machine that wrote this record) |`,
    `| Started, finished | ${summary.startedAt}, ${summary.finishedAt} |`,
    `| Exit code | ${summary.exitCode} |`,
    `| Totals | ${summary.totals.pass} pass, ${summary.totals.fail} fail, ${summary.totals.unavailable} unavailable |`,
    ""
  )
  if (env.note) push(env.note, "")

  push(
    "## Journeys",
    "",
    "| Journey | Result | Reason | Checks | Historical | Scenarios |",
    "| --- | --- | --- | --- | --- | --- |"
  )
  for (const r of results) {
    const historical = r.historical
      ? `${r.historical.id}: reproducedOnHead ${r.historical.reproducedOnHead}`
      : "-"
    const checks = r.checks
      ? `${r.checks.passed} passed, ${r.checks.failed} failed, ${r.checks.skipped} skipped`
      : "-"
    push(
      `| \`${r.journey}\` | ${r.result} | ${cell(r.reason) || "-"} | ${checks} | ${historical} | ${r.scenarios.join(", ")} |`
    )
  }

  push(
    "",
    "## Acceptance ids",
    "",
    "`unavailable` is not a pass. An id with several journeys takes the worst result. `not run` means no selected journey declares the id on this run.",
    "",
    "| id | kind | Result on this commit | Journeys | Catalogue status |",
    "| --- | --- | --- | --- | --- |"
  )
  for (const entry of catalogue.entries) {
    const ran = entry.journeys
      .map((id) => byJourney.get(id))
      .filter((r) => r !== undefined)
    const outcome = aggregate(ran.map((r) => r.result))
    const journeys =
      ran.map((r) => `\`${r.journey}\` ${r.result}`).join(", ") || "-"
    push(
      `| \`${entry.id}\` | ${entry.kind} | ${describeEntry(entry, outcome)} | ${journeys} | ${entry.status} |`
    )
  }
  const known = new Set(catalogue.entries.flatMap((e) => e.journeys))
  const uncatalogued = results.filter((r) => !known.has(r.journey))
  if (uncatalogued.length > 0) {
    push(
      "",
      `Journeys in this run that no catalogue row lists: ${uncatalogued.map((r) => `\`${r.journey}\``).join(", ")}.`
    )
  }

  const historical = results.filter((r) => r.historical)
  push("", "## Historical findings", "")
  if (historical.length === 0) {
    push("No historical journey ran.")
  } else {
    push(
      "A finding counts as resolved only when its journey passed on this commit.",
      "",
      "| id | Journey | Result | Verdict |",
      "| --- | --- | --- | --- |"
    )
    for (const r of historical) {
      const kind =
        catalogue.entries.find((e) => e.id === r.historical.id)?.kind ??
        "defect"
      const verdict =
        r.result === "pass"
          ? "not reproduced: resolved on this commit"
          : r.result === "fail"
            ? kind === "observation"
              ? "observation reproduced (not a defect)"
              : "still reproduces"
            : "unknown: unavailable, not resolved"
      push(
        `| \`${r.historical.id}\` | \`${r.journey}\` | ${r.result} | ${verdict} |`
      )
    }
  }

  push(
    "",
    "## What is kept",
    "",
    "`summary.json`, `summary.md` and `journeys/*.json` are copied unchanged from the run. Logs, screenshots, traces and session files are not kept, so the `evidence` paths inside the JSON point at the original, gitignored run directory (`.artifacts/journeys/" +
      summary.runId +
      "/`).",
    ""
  )
  return lines.join("\n")
}

export function writeRecord({ runDir, outDir, label, root, note }) {
  const { errors, results } = validateRunDir(runDir)
  if (errors.length > 0) {
    throw new Error(`run directory is not valid:\n  ${errors.join("\n  ")}`)
  }
  const summary = JSON.parse(readFileSync(join(runDir, "summary.json"), "utf8"))
  if (summary.revision.dirty || results.some((r) => r.revision.dirty)) {
    throw new Error("the run used a dirty tree and does not count as evidence")
  }
  if (results.some((r) => r.revision.commit !== summary.revision.commit)) {
    throw new Error("journeys in this run ran on different commits")
  }
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(label)) {
    throw new Error("label must be lowercase kebab-case")
  }

  const name = `${summary.finishedAt.slice(0, 10)}-${summary.revision.commit.slice(0, 7)}-${label}`
  const target = join(outDir, name)
  if (existsSync(target)) throw new Error(`${target} already exists`)

  const catalogue = parseCatalogue(
    readFileSync(join(root, "docs/qa/acceptance-ids.md"), "utf8")
  )
  const record = renderRecord({
    summary,
    results,
    catalogue,
    env: {
      label,
      note,
      node: process.version,
      pnpm: pnpmVersion(),
    },
  })

  const files = [
    "summary.json",
    "summary.md",
    ...results.map((r) => `journeys/${r.journey}.json`),
  ]
  for (const file of files) {
    if (containsSecret(readFileSync(join(runDir, file), "utf8"))) {
      throw new Error(`${file} looks like it holds a key or token`)
    }
  }
  mkdirSync(join(target, "journeys"), { recursive: true })
  for (const file of files) copyFileSync(join(runDir, file), join(target, file))
  writeFileSync(join(target, "record.md"), record)
  return target
}

if (resolve(process.argv[1] ?? "") === fileURLToPath(import.meta.url)) {
  const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..")
  const args = process.argv.slice(2)
  const flag = (name) => {
    const i = args.indexOf(name)
    return i === -1 ? undefined : args[i + 1]
  }
  const runDir = args.find(
    (a, i) => !a.startsWith("--") && !args[i - 1]?.startsWith("--")
  )
  const label = flag("--label")
  if (!runDir || !label) {
    console.error(
      "usage: node tests/journeys/evidence-record.mjs <run-dir> --label <slug> [--out docs/qa/evidence] [--note <text>]"
    )
    process.exit(2)
  }
  try {
    const target = writeRecord({
      runDir: resolve(runDir),
      outDir: resolve(root, flag("--out") ?? "docs/qa/evidence"),
      label,
      root,
      note: flag("--note"),
    })
    console.log(`Wrote ${target}`)
  } catch (error) {
    console.error(`✗ ${error.message}`)
    process.exit(1)
  }
}
