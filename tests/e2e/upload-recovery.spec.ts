  test("retry after a network failure keeps the asset; cancel before and during upload never finalises", async ({
    browser,
    baseURL,
  }) => {
    test.setTimeout(180_000)
    const { staff } = await newStaff("e2e-upl-retry")
    const page = await signIn(browser, staff, baseURL!)
    const actions = watchActions(page)

    // --- Retry: every PUT fails at the network level until released.
    let offline = true
    let attempts = 0
    await page.route(SIGNED_PUT, async (route) => {
      attempts++
      if (offline) await route.abort("internetdisconnected")
      else await route.continue()
    })
    let dialog = await openUploadDialog(page)
    await dialog
      .getByLabel("Choose photos or videos")
      .setInputFiles(file("retry.jpg"))
    await dialog.getByRole("button", { name: "Upload 1 file" }).click()
    // The transport retries a dropped PUT itself (0, 3, 5, 10, 20 s), then
    // reports the failure.
    await expect(row(dialog, "retry.jpg")).toContainText(
      "Failed — The connection was interrupted.",
      { timeout: 60_000 }
    )
    expect(attempts).toBe(6)
    const [reserved] = await rowsOf(staff.id)
    expect(reserved).toMatchObject({
      original_filename: "retry.jpg",
      upload_state: "uploading",
    })
    expect(actions.finalises()).toHaveLength(0)

    offline = false
    await dialog.getByRole("button", { name: "Retry retry.jpg" }).click()
    await expectSummary(dialog, "1 uploaded", 30_000)
    const afterRetry = await rowsOf(staff.id)
    expect(afterRetry).toHaveLength(1)
    expect(afterRetry[0]).toMatchObject({
      id: reserved.id,
      upload_state: "ready",
    })
    expect(actions.finalises()).toHaveLength(1)
    await dialog.getByRole("button", { name: "Done" }).click()
    await page.unroute(SIGNED_PUT)

    // --- Cancel: A while its reservation is in flight, B while its bytes are
    // in flight, C while it waits in the queue (2 transfers at a time).
    let heldReserve: Route | null = null
    let heldPut: Route | null = null
    await page.route(
      (url) => url.pathname === "/staff",
      async (route) => {
        const req = route.request()
        if (
          req.method() === "POST" &&
          (req.postData() ?? "").includes("cancel-a.jpg")
        ) {
          heldReserve = route
          return
        }
        await route.continue()
      }
    )
    await page.route(SIGNED_PUT, async (route) => {
      heldPut = route
    })
    const before = actions.bodies.length
    dialog = await openUploadDialog(page)
    await dialog
      .getByLabel("Choose photos or videos")
      // B first: Next dispatches Server Functions one at a time per client,
      // so B's reserve must not queue behind A's held one.
      .setInputFiles([
        file("cancel-b.jpg"),
        file("cancel-a.jpg"),
        file("eleventh.jpg"),
      ])
    await dialog.getByRole("button", { name: "Upload 3 files" }).click()
    await expect
      .poll(() => ({ reserve: heldReserve !== null, put: heldPut !== null }), {
        timeout: 30_000,
      })
      .toEqual({ reserve: true, put: true })
    await expect(row(dialog, "eleventh.jpg")).toContainText("Waiting")
    await dialog.getByRole("button", { name: "Cancel eleventh.jpg" }).click()
    await dialog.getByRole("button", { name: "Cancel cancel-a.jpg" }).click()
    await dialog.getByRole("button", { name: "Cancel cancel-b.jpg" }).click()
    for (const name of ["cancel-a.jpg", "cancel-b.jpg", "eleventh.jpg"]) {
      await expect(row(dialog, name)).toContainText("Cancelled")
    }
    // Let the held reservation reach the server after the cancel.
    await heldReserve!.continue()
    await heldPut!.abort().catch(() => {})
    await expect(dialog.getByRole("status")).toHaveText(
      "0 uploaded · 3 cancelled"
    )
    await sleep(2_000)

    const sent = actions.bodies.slice(before)
    expect(sent.filter((b) => b.includes('"assetId"'))).toHaveLength(0)
    expect(sent.filter((b) => b.includes("eleventh.jpg"))).toHaveLength(0)
    const rows = await rowsOf(staff.id)
    const cancelled = rows.filter((r) =>
      ["cancel-a.jpg", "cancel-b.jpg"].includes(r.original_filename)
    )
    expect(cancelled).toHaveLength(2)
    for (const r of cancelled) {
      expect(r.upload_state).toBe("uploading")
      expect(await objectsOf(staff.id, r.id)).toEqual([])
    }
    expect(rows.map((r) => r.original_filename)).not.toContain("eleventh.jpg")
    await dialog.getByRole("button", { name: "Done" }).click()

    // Until cleanup, the portfolio lists them as unfinished, never ready.
    const portfolio = page.getByRole("list", { name: "Your portfolio" })
    await page.reload()
    await expect(
      portfolio.getByRole("button", { name: /^Photo, cancel-.*Uploading$/ })
    ).toHaveCount(2)

    // Cleanup (24 h window) removes the abandoned reservations.
    const { error } = await admin.rpc("prepare_media_cleanup", {
      p_abandoned_after: "24 hours",
      p_limit: 100,
      p_now: new Date(Date.now() + 25 * 60 * 60 * 1000).toISOString(),
    })
    expect(error).toBeNull()
    for (const r of cancelled) {
      const { data } = await admin
        .from("media_assets")
        .select("deleted_at")
        .eq("id", r.id)
        .single()
      expect(data!.deleted_at).not.toBeNull()
    }
    await page.reload()
    await expect(portfolio.getByRole("button")).toHaveCount(1)
    await expect(
      portfolio.getByRole("button", { name: /^Photo, retry\.jpg/ })
    ).toBeVisible()
    await page.context().close()
  })

  test("TUS: an interrupted chunk resumes from the offset; a lost connection shows Retry; a reload resumes when the file is chosen again", async ({
    browser,
    baseURL,
  }, testInfo) => {
    test.setTimeout(240_000)
    const { staff } = await newStaff("e2e-upl-tus")
    const page = await signIn(browser, staff, baseURL!)
    const storage = watchStorage(page)
    const video = file("tus-video.mp4")
    const size = (await readFile(video)).byteLength
    const chunks = Math.ceil(size / CHUNK)
    expect(chunks).toBeGreaterThanOrEqual(4)
    const patches = () =>
      storage.log
        .filter((r) => TUS.test(r.url) && r.method === "PATCH")
        .map((r) => r.offset)
    const methods = () =>
      storage.log.filter((r) => TUS.test(r.url)).map((r) => r.method)

    // --- 1. One chunk's connection drops mid-transfer: tus-js-client asks the
    // server for its offset (HEAD) and continues from there.
    let dropped = false
    await page.route(TUS, async (route) => {
      const req = route.request()
      if (
        !dropped &&
        req.method() === "PATCH" &&
        req.headers()["upload-offset"] === String(2 * CHUNK)
      ) {
        dropped = true
        return route.abort("connectionreset")
      }
      await route.continue()
    })
    let dialog = await openUploadDialog(page)
    await dialog.getByLabel("Choose photos or videos").setInputFiles(video)
    await dialog.getByRole("button", { name: "Upload 1 file" }).click()
    await expectSummary(dialog, "1 uploaded", 60_000)
    expect(patches()).toEqual([
      0,
      CHUNK,
      2 * CHUNK,
      ...Array.from({ length: chunks - 2 }, (_, i) => (i + 2) * CHUNK),
    ])
    expect(methods().filter((m) => m === "POST")).toHaveLength(1)
    expect(methods().indexOf("HEAD")).toBeGreaterThan(
      methods().indexOf("PATCH")
    )
    await dialog.getByRole("button", { name: "Done" }).click()
    await page.unroute(TUS)
    expect((await rowsOf(staff.id)).map((r) => r.upload_state)).toEqual([
      "ready",
    ])

    // --- 2. The connection stays down past the client's retries: the file
    // fails with the action to take, and Retry resumes the same asset.
    storage.reset()
    let down = true
    await page.route(TUS, async (route) => {
      const req = route.request()
      const offset = Number(req.headers()["upload-offset"] ?? 0)
      if (down && req.method() === "PATCH" && offset >= CHUNK)
        return route.abort("internetdisconnected")
      await route.continue()
    })
    dialog = await openUploadDialog(page)
    await dialog.getByLabel("Choose photos or videos").setInputFiles(video)
    await dialog.getByRole("button", { name: "Upload 1 file" }).click()
    await expect(row(dialog, "tus-video.mp4")).toContainText(
      "Failed — The connection was interrupted. Check your connection, then retry: the upload continues where it stopped.",
      { timeout: 90_000 }
    )
    await dialog.screenshot({ path: testInfo.outputPath("tus-failed.png") })
    const interrupted = (await rowsOf(staff.id)).at(-1)!
    expect(interrupted.upload_state).toBe("uploading")
    down = false
    storage.reset()
    await dialog.getByRole("button", { name: "Retry tus-video.mp4" }).click()
    await expectSummary(dialog, "1 uploaded", 60_000)
    expect(methods()[0]).toBe("HEAD")
    expect(methods()).not.toContain("POST")
    expect(patches()[0]).toBe(CHUNK)
    let rows = await rowsOf(staff.id)
    expect(rows).toHaveLength(2)
    expect(rows[1]).toMatchObject({ id: interrupted.id, upload_state: "ready" })
    await dialog.getByRole("button", { name: "Done" }).click()
    await page.unroute(TUS)

    // --- 3. A reload mid-transfer ends it. The portfolio shows the upload as
    // unfinished (server state), and choosing the same file again resumes
    // the same asset from the stored offset.
    storage.reset()
    let held = false
    await page.route(TUS, async (route) => {
      const req = route.request()
      if (
        req.method() === "PATCH" &&
        req.headers()["upload-offset"] === String(2 * CHUNK)
      ) {
        held = true
        return // never answered: the tab goes away mid-chunk
      }
      await route.continue()
    })
    dialog = await openUploadDialog(page)
    await dialog.getByLabel("Choose photos or videos").setInputFiles(video)
    await dialog.getByRole("button", { name: "Upload 1 file" }).click()
    await expect.poll(() => held, { timeout: 30_000 }).toBe(true)
    page.once("dialog", (d) => void d.accept()) // beforeunload guard
    await page.reload()
    await page.unroute(TUS)
    rows = await rowsOf(staff.id)
    expect(rows).toHaveLength(3)
    const unfinished = rows[2]
    expect(unfinished.upload_state).toBe("uploading")
    const portfolio = page.getByRole("list", { name: "Your portfolio" })
    await expect(
      portfolio.getByRole("button", {
        name: /^Video, tus-video\.mp4.*Uploading$/,
      })
    ).toHaveCount(1)
    // A fresh context (another device or browser) shows the same states.
    const other = await signIn(browser, staff, baseURL!)
    const otherPortfolio = other.getByRole("list", { name: "Your portfolio" })
    await expect(
      otherPortfolio.getByRole("button", { name: /Uploading$/ })
    ).toHaveCount(1)
    await expect(
      otherPortfolio.getByRole("button", { name: /^Video, tus-video\.mp4/ })
    ).toHaveCount(3)
    await other.context().close()

    storage.reset()
    dialog = await openUploadDialog(page)
    await dialog.getByLabel("Choose photos or videos").setInputFiles(video)
    await dialog.getByRole("button", { name: "Upload 1 file" }).click()
    await expectSummary(dialog, "1 uploaded", 60_000)
    expect(methods()[0]).toBe("HEAD")
    expect(methods()).not.toContain("POST")
    expect(patches()[0]).toBe(2 * CHUNK)
    rows = await rowsOf(staff.id)
    expect(rows).toHaveLength(3)
    expect(rows[2]).toMatchObject({ id: unfinished.id, upload_state: "ready" })
    await dialog.getByRole("button", { name: "Done" }).click()
    await expect(
      portfolio.getByRole("button", { name: /Uploading$/ })
    ).toHaveCount(0)
    await page.context().close()
  })

