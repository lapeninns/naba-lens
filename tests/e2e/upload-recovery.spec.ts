async function signIn(
  browser: Browser,
  identity: TestIdentity,
  baseURL: string,
  home: RegExp = /\/staff$/
) {
  let link = await admin.auth.admin.generateLink({
    type: "magiclink",
    email: identity.email,
  })
  for (let i = 0; link.error?.status === 504 && i < 3; i++) {
    link = await admin.auth.admin.generateLink({
      type: "magiclink",
      email: identity.email,
    })
  }
  if (link.error) throw link.error
  const context = await browser.newContext({ baseURL })
  const page = await context.newPage()
  await openEmailLink(
    page,
    `/auth/confirm?token_hash=${link.data.properties.hashed_token}&type=email`
  )
  await expect(page).toHaveURL(home)
  return page
}

async function newStaff(label: string) {
  const venue = await createVenue(admin, label)
  const staff = await createIdentity(admin, {
    label,
    role: "staff",
    venueId: venue.id,
    session: false,
  })
  return { venue, staff }
}

async function rowsOf(uploaderId: string) {
  const { data, error } = await admin
    .from("media_assets")
    .select(
      "id, original_filename, media_type, upload_state, validated_mime_type, size_bytes, original_path, preview_path, thumbnail_path, deleted_at"
    )
    .eq("uploader_id", uploaderId)
    .order("created_at")
  if (error) throw error
  return data
}

async function objectsOf(uploaderId: string, assetId: string) {
  const { data, error } = await admin.storage
    .from("media")
    .list(`${uploaderId}/${assetId}`)
  if (error) throw error
  return data.map((o) => o.name).sort()
}

async function openUploadDialog(page: Page) {
  await page
    .getByRole("button", { name: "Upload photos or videos" })
    .first()
    .click()
  const dialog = page.getByRole("dialog", { name: "Upload photos or videos" })
  await expect(dialog).toBeVisible()
  return dialog
}

/** The queue row of one file in the upload dialog. */
const row = (dialog: Locator, name: string) =>
  dialog
    .getByRole("list", { name: "Files" })
    .getByRole("listitem")
    .filter({ has: dialog.page().getByText(name, { exact: true }) })

/** Waits for the run to settle; on a mismatch the message lists every file's row. */
async function expectSummary(
  dialog: Locator,
  expected: string,
  timeout = 60_000
) {
  const status = dialog.getByRole("status")
  await expect(status).toBeVisible({ timeout })
  const files = await dialog.getByRole("list", { name: "Files" }).innerText()
  expect(await status.textContent(), files).toBe(expected)
}

/** Records storage upload requests and the most that were in flight at once. */
function watchStorage(page: Page) {
  const inFlight = new Set<Request>()
  const log: { method: string; url: string; offset: number | null }[] = []
  let max = 0
  page.on("request", (r) => {
    if (!STORAGE_UPLOAD.test(r.url()) || r.method() === "OPTIONS") return
    inFlight.add(r)
    max = Math.max(max, inFlight.size)
    const offset = r.headers()["upload-offset"]
    log.push({
      method: r.method(),
      url: r.url(),
      offset: offset === undefined ? null : Number(offset),
    })
  })
  const settle = (r: Request) => inFlight.delete(r)
  page.on("requestfinished", settle)
  page.on("requestfailed", settle)
  return {
    log,
    get max() {
      return max
    },
    reset() {
      log.length = 0
      max = inFlight.size
    },
  }
}

/** Server Function calls (reserve/finalise) posted from the staff page. */
function watchActions(page: Page) {
  const bodies: string[] = []
  page.on("request", (r) => {
    if (r.method() === "POST" && r.headers()["next-action"]) {
      bodies.push(r.postData() ?? "")
    }
  })
  return {
    bodies,
    finalises: () => bodies.filter((b) => b.includes('"assetId"')),
  }
}

